#!/usr/bin/env node
// Build the design system:
//   design/tokens.json  -> public/tokens.css   (CSS variables, references kept as var() chains)
//   design/icons/*.svg  -> public/icons.svg    (one <symbol> sprite, used as <svg><use href="icons.svg#i-name">)
// Also checks text/background contrast for both themes (WCAG AA, 4.5:1) and fails on a miss.
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const tokens = JSON.parse(fs.readFileSync(path.join(__dirname, 'tokens.json'), 'utf8'));

// ---------- tokens -> CSS ----------
const varName = parts => '--' + parts.filter(p => p !== 'semantic' && p !== 'component').join('-').replace(/^primitive-/, 'p-');
function walk(obj, prefix, out) {
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith('$')) continue;
    if (v && typeof v === 'object' && '$value' in v) out.push([[...prefix, k], v.$value]);
    else if (v && typeof v === 'object') walk(v, [...prefix, k], out);
  }
  return out;
}
const ref = v => typeof v === 'string' ? v.replace(/\{([^}]+)\}/g, (_, p) => `var(${varName(p.split('.'))})`) : v;
// resolve to a literal (for contrast checks)
function resolve(v, themeOverride) {
  if (typeof v !== 'string') return v;
  const m = v.match(/^\{([^}]+)\}$/);
  if (!m) return v;
  const parts = m[1].split('.');
  let node = parts[0] === 'semantic' && themeOverride ? (get(themeOverride, parts.slice(1)) || get(tokens, parts)) : get(tokens, parts);
  if (!node) throw new Error('unresolved token ' + m[1]);
  return resolve(node.$value, themeOverride);
}
function get(obj, parts) { return parts.reduce((o, k) => o && o[k], obj); }

const prim = walk(tokens.primitive, ['primitive'], []);
const sem = walk(tokens.semantic, ['semantic'], []);
const comp = walk(tokens.component, ['component'], []);
const light = walk(tokens.themes.light, ['semantic'], []);
const block = rows => rows.map(([p, v]) => `  ${varName(p)}: ${ref(v)};`).join('\n');

const css = `/* JARVIS design tokens — generated by design/build.cjs from design/tokens.json. Do not edit. */

/* Layer 1 · primitives (raw values) */
:root {
${block(prim)}
}

/* Layer 2 · semantic (dark theme is the default) */
:root {
  color-scheme: dark;
${block(sem)}
}

/* Layer 2 · semantic overrides for the light theme */
:root[data-theme="light"] {
  color-scheme: light;
${block(light)}
}

/* Layer 3 · components */
:root {
${block(comp)}
}
`;
fs.writeFileSync(path.join(ROOT, 'public', 'tokens.css'), css);

// ---------- contrast check ----------
const hex2rgb = h => { h = h.replace('#', ''); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16) / 255); };
const lum = h => { const [r, g, b] = hex2rgb(h).map(c => c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const PAIRS = [
  ['fg', 'bg'], ['fg', 'surface-1'], ['fg', 'surface-2'], ['fg', 'surface-3'],
  ['fg-muted', 'bg'], ['fg-muted', 'surface-1'], ['fg-muted', 'surface-2'],
  ['primary', 'surface-1'], ['primary', 'surface-2'], ['on-primary', 'primary'],
  ['claude', 'surface-2'], ['codex', 'surface-2'], ['sub', 'surface-1'],
  ['success', 'surface-2'], ['warning', 'surface-2'], ['danger', 'surface-2'], ['info', 'surface-2'],
];
let failed = 0;
for (const [theme, override] of [['dark', null], ['light', tokens.themes.light]]) {
  const c = name => resolve(`{semantic.color.${name}}`, override);
  for (const [fg, bg] of PAIRS) {
    const r = ratio(c(fg), c(bg));
    if (r < 4.5) { failed++; console.log(`  FAIL ${theme.padEnd(5)} ${fg} on ${bg}: ${r.toFixed(2)}:1 (${c(fg)} / ${c(bg)})`); }
  }
}

// ---------- icons -> sprite ----------
const iconDir = path.join(__dirname, 'icons');
const symbols = fs.readdirSync(iconDir).filter(f => f.endsWith('.svg')).sort().map(f => {
  const svg = fs.readFileSync(path.join(iconDir, f), 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim().replace(/\s*\n\s*/g, '');
  return `<symbol id="i-${f.replace(/\.svg$/, '')}" viewBox="0 0 24 24">${inner}</symbol>`;
});
fs.writeFileSync(path.join(ROOT, 'public', 'icons.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg"><!-- Lucide icons (ISC license, see design/icons/LICENSE-lucide.txt) -->\n${symbols.join('\n')}\n</svg>\n`);

console.log(`tokens: ${prim.length} primitive, ${sem.length} semantic (+${light.length} light), ${comp.length} component -> public/tokens.css`);
console.log(`icons: ${symbols.length} -> public/icons.svg`);
console.log(failed ? `contrast: ${failed} pair(s) below 4.5:1` : `contrast: all ${PAIRS.length * 2} text pairs >= 4.5:1 (dark + light)`);
process.exit(failed ? 1 : 0);
